/****************************************************************************
 * oled_display.c - SSD1306 0.96" I2C OLED (128x64, addr 0x3C) for FireEye
 *
 * Uses the NuttX I2C character device (/dev/i2c1) with I2CIOC_TRANSFER.
 * Note: I2C1 is used because I2C0 shares PB6/PB7 with the USART0 console.
 ****************************************************************************/

#include <nuttx/config.h>
#include <errno.h>
#include <fcntl.h>
#include <stdio.h>
#include <string.h>
#include <sys/ioctl.h>
#include <unistd.h>

#include <nuttx/i2c/i2c_master.h>
#include "include/oled_display.h"

#define I2C_DEV_PATH      "/dev/i2c1"

static int g_i2c_fd = -1;
static uint8_t g_i2c_addr = OLED_I2C_ADDR;   /* 默认 0x3C，失败会重试 0x3D */
static uint8_t g_fb[OLED_WIDTH * OLED_HEIGHT / 8];

/* SSD1306 command prefix */
#define CMD_PREFIX        0x00
#define DATA_PREFIX       0x40

/* I2C 时钟：必须显式设置，GD32 驱动用它计算分频；100kHz 在杜邦线环境更稳 */
#define OLED_I2C_FREQ     100000

static int oled_write(uint8_t *buf, uint16_t len)
{
  struct i2c_transfer_s xfer;
  struct i2c_msg_s msg;
  int ret;

  if (g_i2c_fd < 0)
    {
      return -ENODEV;
    }

  msg.addr      = g_i2c_addr;
  msg.flags     = 0;
  msg.buffer    = buf;
  msg.length    = len;
  msg.frequency = OLED_I2C_FREQ;

  xfer.msgv      = &msg;
  xfer.msgc      = 1;

  ret = ioctl(g_i2c_fd, I2CIOC_TRANSFER, (unsigned long)(uintptr_t)&xfer);
  return ret;
}

static int oled_cmd(uint8_t c)
{
  uint8_t b[2];

  b[0] = CMD_PREFIX;
  b[1] = c;
  return oled_write(b, 2);
}

/* 发送一串命令：每次最多打包 15 条（缓冲区 1+15），循环发完为止。
 * 注意：旧实现只发一次且按 n+1 长度发送，会越界并丢掉末尾的电荷泵命令。 */

static int oled_cmds(const uint8_t *cmds, size_t n)
{
  uint8_t b[1 + 15];
  size_t sent = 0;

  while (sent < n)
    {
      size_t chunk = n - sent;
      size_t i;
      int ret;

      if (chunk > 15)
        {
          chunk = 15;
        }

      b[0] = CMD_PREFIX;
      for (i = 0; i < chunk; i++)
        {
          b[1 + i] = cmds[sent + i];
        }

      ret = oled_write(b, (uint16_t)(chunk + 1));
      if (ret < 0)
        {
          return ret;
        }

      sent += chunk;
    }

  return 0;
}

int oled_init(void)
{
  static const uint8_t init_cmds[] = {
    0xAE,             /* display off */
    0x20, 0x00,       /* memory mode: horizontal */
    0xB0,             /* page0 */
    0xC8,             /* COM scan dir */
    0x00, 0x10,       /* low/high column */
    0x40,             /* start line 0 */
    0x81, 0x7F,       /* contrast */
    0xA1,             /* segment remap */
    0xA6,             /* normal display */
    0xA8, 0x3F,       /* multiplex 64 */
    0xA4,             /* resume from RAM */
    0xD3, 0x00,       /* display offset */
    0xD5, 0xF0,       /* clock div */
    0xD9, 0x22,       /* pre-charge */
    0xDA, 0x12,       /* com pins */
    0xDB, 0x20,       /* vcomh */
    0x8D, 0x14,       /* charge pump：必须发出去，否则屏不亮 */
    0xAF,             /* display on */
  };
  int ret;

  g_i2c_fd = open(I2C_DEV_PATH, O_RDWR);
  if (g_i2c_fd < 0)
    {
      return -ENODEV;
    }

  /* SSD1306 上电后需要稳定时间 */

  usleep(50000);

  /* 先按 0x3C 初始化，失败再试 0x3D（两种模块都很常见） */

  g_i2c_addr = OLED_I2C_ADDR;
  ret = oled_cmds(init_cmds, sizeof(init_cmds));
  if (ret < 0)
    {
      g_i2c_addr = 0x3D;
      ret = oled_cmds(init_cmds, sizeof(init_cmds));
    }

  if (ret < 0)
    {
      close(g_i2c_fd);
      g_i2c_fd = -1;
      return -EIO;
    }

  memset(g_fb, 0, sizeof(g_fb));
  oled_refresh();
  oled_cmd(0xAF);       /* display on */
  return 0;
}

void oled_clear(void)
{
  memset(g_fb, 0, sizeof(g_fb));
  oled_refresh();
}

void oled_fill(uint8_t on)
{
  memset(g_fb, on ? 0xFF : 0x00, sizeof(g_fb));
  oled_refresh();
}

void oled_refresh(void)
{
  static const uint8_t window_cmds[] = {
    0x21, 0x00, 0x7F,   /* 列地址 0..127 */
    0x22, 0x00, 0x07,   /* 页地址 0..7   */
  };
  uint8_t page_block[1 + 1 + OLED_WIDTH];
  int page, col;

  if (g_i2c_fd < 0)
    {
      return;
    }

  oled_cmds(window_cmds, sizeof(window_cmds));

  for (page = 0; page < 8; page++)
    {
      page_block[0] = DATA_PREFIX;
      for (col = 0; col < OLED_WIDTH; col++)
        {
          page_block[1 + col] = g_fb[page * OLED_WIDTH + col];
        }
      oled_write(page_block, 1 + OLED_WIDTH);
    }
}

